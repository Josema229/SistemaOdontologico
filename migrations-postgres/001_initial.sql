CREATE TABLE IF NOT EXISTS branches (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS specialties (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS dentists (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, specialty_id INTEGER NOT NULL REFERENCES specialties(id),
 active INTEGER NOT NULL DEFAULT 1 CHECK(active IN (0,1))
);
CREATE TABLE IF NOT EXISTS users (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, email TEXT NOT NULL,
 password_hash TEXT NOT NULL, role TEXT NOT NULL CHECK(role IN ('recepcionista','odontologo')),
 dentist_id INTEGER UNIQUE REFERENCES dentists(id),
 CHECK((role='odontologo' AND dentist_id IS NOT NULL) OR (role='recepcionista' AND dentist_id IS NULL))
);
CREATE TABLE IF NOT EXISTS sessions (
 token_hash TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 expires_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_expiry ON sessions(expires_at);
CREATE TABLE IF NOT EXISTS dentist_branches (
 dentist_id INTEGER NOT NULL REFERENCES dentists(id), branch_id INTEGER NOT NULL REFERENCES branches(id),
 PRIMARY KEY(dentist_id,branch_id)
);
CREATE TABLE IF NOT EXISTS availabilities (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, dentist_id INTEGER NOT NULL, branch_id INTEGER NOT NULL,
 weekday INTEGER NOT NULL CHECK(weekday BETWEEN 0 AND 6),
 start_time TEXT NOT NULL, end_time TEXT NOT NULL,
 CHECK(start_time >= '08:00' AND end_time <= '20:00' AND start_time < end_time),
 FOREIGN KEY(dentist_id,branch_id) REFERENCES dentist_branches(dentist_id,branch_id)
);
CREATE INDEX IF NOT EXISTS availability_lookup ON availabilities(dentist_id,weekday);
CREATE TABLE IF NOT EXISTS patients (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, first_name TEXT NOT NULL, last_name TEXT NOT NULL,
 identity_number TEXT NOT NULL UNIQUE, phone TEXT NOT NULL DEFAULT '',
 dentist_id INTEGER REFERENCES dentists(id), created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS patients_names ON patients(last_name,first_name);
CREATE TABLE IF NOT EXISTS appointments (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, patient_id INTEGER NOT NULL REFERENCES patients(id),
 dentist_id INTEGER NOT NULL, branch_id INTEGER NOT NULL,
 date TEXT NOT NULL, start_time TEXT NOT NULL, end_time TEXT NOT NULL, reason TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'programado' CHECK(status IN ('programado','atendido','cancelado','ausente')),
 created_by INTEGER NOT NULL REFERENCES users(id), created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK(start_time >= '08:00' AND end_time <= '20:00' AND start_time < end_time),
 FOREIGN KEY(dentist_id,branch_id) REFERENCES dentist_branches(dentist_id,branch_id)
);
CREATE INDEX IF NOT EXISTS appointment_schedule ON appointments(dentist_id,date,start_time,end_time,status);
CREATE INDEX IF NOT EXISTS appointment_patient ON appointments(patient_id);
CREATE INDEX IF NOT EXISTS appointment_branch ON appointments(branch_id,date);
CREATE TABLE IF NOT EXISTS appointment_changes (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, appointment_id INTEGER NOT NULL REFERENCES appointments(id),
 old_date TEXT NOT NULL, old_start TEXT NOT NULL, old_end TEXT NOT NULL,
 new_date TEXT NOT NULL, new_start TEXT NOT NULL, new_end TEXT NOT NULL,
 user_id INTEGER NOT NULL REFERENCES users(id), changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS clinical_visits (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, appointment_id INTEGER NOT NULL UNIQUE REFERENCES appointments(id),
 patient_id INTEGER NOT NULL REFERENCES patients(id), dentist_id INTEGER NOT NULL REFERENCES dentists(id),
 attended_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, treatment TEXT NOT NULL,
 next_date TEXT, next_procedure TEXT
);
CREATE INDEX IF NOT EXISTS clinical_patient ON clinical_visits(patient_id,attended_at);
CREATE TABLE IF NOT EXISTS login_attempts (key TEXT PRIMARY KEY, attempts INTEGER NOT NULL, reset_at BIGINT NOT NULL);

